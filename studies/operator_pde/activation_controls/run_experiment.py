def run_stage(args: argparse.Namespace) -> None:
    if args.stage == "validate":
        validate_stage()
    elif args.stage == "pde-primary":
        _run_jobs(
            _pde_jobs("primary"),
            parallel_jobs=args.parallel_pde,
            dense_workers=args.dense_workers,
        )
    elif args.stage == "pde-scramble":
        _run_jobs(
            _pde_jobs("scramble"),
            parallel_jobs=args.parallel_pde,
            dense_workers=args.dense_workers,
        )
    elif args.stage == "pde-n32":
        _run_jobs(
            _pde_jobs("N32"),
            parallel_jobs=args.parallel_pde,
            dense_workers=args.dense_workers,
        )
    elif args.stage == "seal-pde":
        seal_pde()
    elif args.stage == "dense-primary":
        _run_jobs(
            _dense_jobs("primary"),
            parallel_jobs=args.parallel_dense,
            dense_workers=args.dense_workers,
        )
    elif args.stage == "dense-depth":
        _run_jobs(
            _dense_jobs("physical_depth"),
            parallel_jobs=args.parallel_dense,
            dense_workers=args.dense_workers,
        )
    elif args.stage == "dense-width":
        _run_jobs(
            _dense_jobs("width"),
            parallel_jobs=args.parallel_dense,
            dense_workers=args.dense_workers,
        )
    elif args.stage == "seal-dense":
        seal_dense()
    elif args.stage == "analyze":
        analyze_stage()
    else:
        validate_stage()
        for role in ("primary", "scramble", "N32"):
            _run_jobs(
                _pde_jobs(role),
                parallel_jobs=args.parallel_pde,
                dense_workers=args.dense_workers,
            )
        seal_pde()
        for role in ("primary", "physical_depth", "width"):
            _run_jobs(
                _dense_jobs(role),
                parallel_jobs=args.parallel_dense,
                dense_workers=args.dense_workers,
            )
        seal_dense()
        analyze_stage()


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Run the frozen activation-linearity experiment with strict, "
            "metadata-validated resume."
        )
    )
    parser.add_argument(
        "stage",
        nargs="?",
        default="all",
        choices=(
            "all",
            "validate",
            "pde-primary",
            "pde-scramble",
            "pde-n32",
            "seal-pde",
            "dense-primary",
            "dense-depth",
            "dense-width",
            "seal-dense",
            "analyze",
        ),
    )
    parser.add_argument("--parallel-pde", type=int, default=3)
    parser.add_argument("--parallel-dense", type=int, default=1)
    parser.add_argument("--dense-workers", type=int, default=4)
    return parser.parse_args(argv)


if __name__ == "__main__":
    run_stage(parse_args())
