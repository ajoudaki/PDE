def _require_seal_common(record: Mapping[str, Any], stage: str) -> None:
    inputs = _require_input_manifest()
    required = {
        "schema_version": 1,
        "stage": stage,
        "dynamics_sha256": inputs["dynamics_sha256"],
        "source_sha256": inputs["source_sha256"],
        "source_files": inputs["source_files"],
        "protocol_sha256": inputs["protocol_sha256"],
        "protocol_files": inputs["protocol_files"],
        "execution_sha256": inputs["execution_sha256"],
        "execution_files": inputs["execution_files"],
        "parent_source_lineage": inputs["parent_source_lineage"],
        "inference_roles": inputs["inference_roles"],
        "input_manifest_sha256": _sha256(INPUT_MANIFEST_PATH),
        "orchestrator_sha256": _sha256(Path(__file__)),
    }
    for key, value in required.items():
        if record.get(key) != value:
            raise IntegrityError(f"{stage} seal mismatch for {key!r}")
    files = record.get("files")
    if not isinstance(files, dict):
        raise IntegrityError(f"{stage} seal has no file map")
    for relative, expected_sha256 in files.items():
        path = ROOT / relative
        if not path.is_file() or _sha256(path) != expected_sha256:
            raise IntegrityError(f"sealed file mismatch: {relative}")


