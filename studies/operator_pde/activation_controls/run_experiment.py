#!/usr/bin/env python3
"""Reproduce the preregistered activation-linearity smoking-gun experiment.

All scientific trajectories are generated by the frozen command-line runners
in ``source/``.  This file only validates inputs, schedules those subprocesses,
checks completed archives, and writes deterministic provenance seals.

Resume policy
-------------
A completed job is skipped only when exactly one archive has the job's logical
identity, every frozen metadata field agrees, its time grid and array shapes
are exact, and every numeric array is finite.  A colliding-but-different
archive, duplicate match, partial archive, changed source/protocol file, or
changed seal is a hard error.
"""

